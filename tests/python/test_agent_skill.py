"""The agent skill in integrations/agent-skill/tomacco names only what exists: every
operation and argument against assets/operations.json, the installed guides against what
install.py installs and the tomacco://docs resources against the MCP server's guides.
Its references/ are generated by tools/build_reference.py from the same file: each
operation is in exactly one, and they are current. SKILL.md is a router and has a word
budget. Its `tomaccoctl call` lines are also held to tomaccoctl's own argument validation
with the other guides, in test_docs_virtual_iphone."""
import importlib.util
import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILL = ROOT / "integrations/agent-skill/tomacco"
SPEC = importlib.util.spec_from_file_location("build_reference", ROOT / "tools/build_reference.py")
build_reference = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(build_reference)
SCHEMAS = {entry["name"]: entry for entry in json.loads((ROOT / "assets/operations.json").read_text(encoding="utf-8"))}
OPERATIONS = set(SCHEMAS)
ERRORS = json.loads((ROOT / "assets/errors.json").read_text(encoding="utf-8"))
REFERENCES = SKILL / "references"
WORD_BUDGET = 1800
# Every argument name of any operation, at any depth: a backticked word in the skill that is not an
# operation, an error code or one of these is a typo or a name that no longer exists.
def argument_names(schema, found):
    if isinstance(schema, dict):
        for key, value in schema.get("properties", {}).items():
            found.add(key)
            argument_names(value, found)
        argument_names(schema.get("items"), found)
    return found


ARGUMENTS = set()
for _entry in SCHEMAS.values():
    argument_names(_entry["inputSchema"], ARGUMENTS)
# Words of results and of the skill's own prose that are neither: result fields, states, modes.
WORDS = {"ready", "missing", "next_steps", "ask_first", "state", "full", "compact", "grouped", "schema",
         "operation", "arguments", "read", "ok", "succeeded", "failed", "cancelled", "timed_out", "ocr",
         "virtual-iphone", "android", "ios", "test", "instrumented-test", "build", "cold", "hierarchy",
         "TOMACCO_MCP_TOOLS", "UDID", "JOB_ID", "pair", "login", "stop", "text", "patch", "device",
         "tomaccoctl", "tomacco", "sdkmanager", "emulator", "adb", "emulator-5554", "performance", "allow_emulator", "mark_stale", "message", "remedy", "code", "id"}
# Each area's file and a word in the description that makes an agent reach for the skill for it.
TRIGGERS = {"project": "Gradle", "device": "screenshots", "android": "emulator", "screen": "OCR",
            "testing": "UI tests", "profile": "macrobenchmark", "release": "keystores", "play": "Play Store",
            "ios": "iPhone over USB", "ios-virtual": "virtual iPhone", "debug": "debugging", "preview": "previews",
            "remote": "remote build", "apple": "App Store", "swift": "Swift on Android"}
# Backticked words that are neither operations nor meant to be: keys, states, codes and commands.
NOT_OPERATIONS = re.compile(r".*[/ {:\"'~]|.*\.(md|json|png)$|--|^[A-Z]")
# Dotted words that are paths into a result, not operations.
RESULT_PATHS = {"dev.example.myapp", "result.id", "error.code", "error.message", "error.remedy"}


def files():
    """The hand-written pages: SKILL.md and workflows.md. references/ is generated."""
    return sorted(SKILL.glob("*.md"))


def read(path):
    return path.read_text(encoding="utf-8")


def call_lines(path):
    """(operation, arguments or None) of each `tomaccoctl call` line, in a code block or not."""
    found = []
    for line in read(path).splitlines():
        match = re.match(r"^\s*tomaccoctl call (\S+)(?: '(\{.*\})')?(?: --\w+)*\s*$", line)
        if match:
            found.append((match.group(1), json.loads(match.group(2)) if match.group(2) else None))
    return found


def reference_sections():
    """{operation: (file name, section text)} over references/."""
    found = {}
    for path in sorted(REFERENCES.glob("*.md")):
        for section in re.split(r"(?m)^### ", read(path))[1:]:
            found.setdefault(section.split("\n", 1)[0].strip(), []).append((path.name, section))
    return found


class AgentSkillTests(unittest.TestCase):
    def test_the_front_matter_names_the_skill_and_when_to_use_it(self):
        text = (SKILL / "SKILL.md").read_text(encoding="utf-8")
        front = re.match(r"---\n(.*?)\n---\n", text, re.S)
        self.assertTrue(front, "SKILL.md starts with YAML front matter")
        self.assertRegex(front.group(1), r"(?m)^name: tomacco$")
        description = front.group(1).split("description:", 1)[1]
        for word in ("Android", "iOS", "virtual iPhone", "screenshots", "UI tests", "tomaccoctl"):
            self.assertIn(word, description)
        for word in ("OCR", "macrobenchmark", "baseline profiles", "Omarchy", "Play Store", "keystores"):
            self.assertIn(word, description)
        for area, word in TRIGGERS.items():
            self.assertIn(word.lower(), description.lower(), f"the description has no trigger for {area}")
        self.assertLess(len(" ".join(description.split())), 1500, "a description that long is always loaded")
        keys = re.findall(r"(?m)^([a-z-]+):", front.group(1))
        self.assertEqual(sorted(keys), ["description", "name"])

    def test_every_backticked_operation_exists(self):
        checked = 0
        for path in files():
            for token in re.findall(r"`([^`\n]+)`", path.read_text(encoding="utf-8")):
                if NOT_OPERATIONS.match(token) or token in RESULT_PATHS:
                    continue
                if "." in token:
                    # Anything dotted that is not a file is meant as an operation.
                    self.assertTrue(token in OPERATIONS, f"{path.name} names {token}, which is no operation")
                    checked += 1
                elif token in OPERATIONS:
                    checked += 1
        self.assertGreater(checked, 40)

    def test_the_task_table_lists_only_operations_and_covers_every_area(self):
        text = read(SKILL / "SKILL.md")
        rows = [line for line in text.split("## Which operation", 1)[1].split("\n## ", 1)[0].splitlines()
                if line.startswith("| ") and "---" not in line][1:]
        self.assertGreater(len(rows), 15)
        for row in rows:
            for token in re.findall(r"`([^`]+)`", row.split("|")[2]):
                self.assertTrue(token in OPERATIONS, f"{token} is no operation: {row}")
        table = "\n".join(rows)
        for path in sorted(REFERENCES.glob("*.md")):
            if path.name not in ("index.md", "errors.md"):
                self.assertIn(f"(references/{path.name})", table, f"the task table does not send an agent to {path.name}")
        for area in {build_reference.skill_area(name) for name in OPERATIONS}:
            self.assertTrue((REFERENCES / f"{area}.md").is_file(), area)

    def test_the_guides_it_points_to_are_installed_and_served(self):
        import sys
        sys.path.insert(0, str(ROOT))
        from install import DOCUMENTS
        text = (SKILL / "SKILL.md").read_text(encoding="utf-8")
        documentation = text.split("## Documentation", 1)[1]
        installed = set(DOCUMENTS.values())
        for name in re.findall(r"`([a-z-]+\.md)`", documentation):
            self.assertIn(name, installed)
        served = set(re.findall(r'name: "([a-z-]+)",\n\s+title: [^\n]+\n\s+description: [^\n]+\n\s+text: include_str!',
                                (ROOT / "native/mcp.rs").read_text(encoding="utf-8")))
        self.assertIn("agents", served)
        for name in re.findall(r"tomacco://docs/([a-z-]+)", text):
            self.assertIn(name, served)
        for link in re.findall(r"\]\(([^)]+)\)", text):
            self.assertTrue((SKILL / link).is_file(), link)

    def test_skill_md_is_a_router_within_its_word_budget(self):
        text = read(SKILL / "SKILL.md")
        words = len(text.split())
        self.assertLessEqual(words, WORD_BUDGET, f"SKILL.md has {words} words; move detail to workflows.md or references/")
        self.assertGreaterEqual(words, 1000)
        for heading in ("## Reach it", "## Jobs", "## Work safely", "## Which operation", "## The core loops",
                        "## Omarchy", "## When it fails"):
            self.assertIn(heading, text)
        for word in ("TOMACCO_MCP_TOOLS", "job.wait", "destructive", "error.code", "remedy", "references/errors.md"):
            self.assertIn(word, text)

    def test_the_operation_count_is_the_schema_count(self):
        counts = re.findall(r"(\d+) typed operations", read(SKILL / "SKILL.md"))
        self.assertEqual(counts, [str(len(OPERATIONS))])
        index = read(REFERENCES / "index.md")
        self.assertIn(f"{len(OPERATIONS)} operations in all", index)

    def test_every_operation_is_in_exactly_one_references_file_with_its_arguments(self):
        sections = reference_sections()
        self.assertEqual(set(sections), OPERATIONS)
        index = read(REFERENCES / "index.md")
        total = 0
        for name, found in sections.items():
            self.assertEqual(len(found), 1, f"{name} is in {[file for file, _ in found]}")
            file, section = found[0]
            self.assertEqual(file, f"{build_reference.skill_area(name)}.md")
            operation = SCHEMAS[name]
            annotations = operation["annotations"]
            if annotations.get("readOnlyHint"):
                self.assertIn("read-only", section.split("\n", 3)[2], name)
            elif annotations.get("destructiveHint"):
                self.assertIn("destructive, ask first", section, name)
            self.assertIn("\n" + build_reference.example_call(operation) + "\n", section, name)
            schema = operation["inputSchema"]
            for key, spec in schema.get("properties", {}).items():
                line = re.search(rf"(?m)^- `{re.escape(key)}` .*$", section)
                self.assertIsNotNone(line, f"{name} lacks {key}")
                self.assertEqual(", required" in line.group(0).split(":")[0], key in schema.get("required", []), f"{name}.{key}")
            total += 1
        self.assertEqual(total, len(OPERATIONS))
        for path in REFERENCES.glob("*.md"):
            if path.name not in ("index.md", "errors.md"):
                count = len(re.findall(r"(?m)^### ", read(path)))
                self.assertRegex(index, rf"\[{path.stem}\]\({path.name}\) \| {count} \|")

    def test_the_errors_file_lists_every_code_with_its_remedy(self):
        text = read(REFERENCES / "errors.md")
        for code, entry in ERRORS.items():
            row = re.search(rf"(?m)^\| `{code}` \| .* \| .* \|$", text)
            self.assertIsNotNone(row, code)
            self.assertIn(" ".join(entry["remedy"].split())[:30].replace("<", "&lt;").replace("*", "\\*"), row.group(0), code)
        self.assertIn(f"{len(ERRORS)} codes", text)

    def test_the_generated_files_are_current(self):
        found = build_reference.stale()
        self.assertEqual(found, [], "stale: %s; run python3 tools/build_reference.py" % ", ".join(found))
        for path in REFERENCES.glob("*.md"):
            self.assertTrue(read(path).startswith("<!-- Generated by tools/build_reference.py"), path.name)
        self.assertEqual({p.name for p in SKILL.iterdir()} - {"references"}, {"SKILL.md", "workflows.md"})

    def test_every_call_in_the_skill_names_a_real_operation_and_its_arguments(self):
        checked = 0
        for path in files():
            for name, arguments in call_lines(path):
                self.assertIn(name, OPERATIONS, f"{path.name}: {name}")
                schema = SCHEMAS[name]["inputSchema"]
                arguments = arguments or {}
                unknown = set(arguments) - set(schema.get("properties", {}))
                self.assertFalse(unknown, f"{path.name}: {name} has no argument {sorted(unknown)}")
                if schema.get("required") and "anyOf" not in schema and "oneOf" not in schema:
                    missing = set(schema["required"]) - set(arguments)
                    self.assertFalse(missing, f"{path.name}: {name} lacks {sorted(missing)}")
                checked += 1
        self.assertGreater(checked, 50)

    def test_every_workflow_covers_the_common_jobs(self):
        text = read(SKILL / "workflows.md")
        used = {name for name, _ in call_lines(SKILL / "workflows.md")}
        for name in ("capabilities", "project.run", "job.wait", "screen.marks", "screen.tap", "screen.ocr",
                     "testing.run", "profile.startup", "profile.macrobenchmark", "profile.baseline_profile",
                     "release.sign", "play.prepare", "ios.virtual.start", "ios.virtual.stop", "ios.device_status",
                     "workflow.run"):
            self.assertIn(name, used)
        for heading in ("## Plan", "## The virtual iPhone", "## A physical iPhone", "## Performance", "## Release"):
            self.assertIn(heading, text)

    def test_every_backticked_word_is_an_operation_an_argument_an_error_or_a_known_term(self):
        for path in files():
            for token in re.findall(r"`([^`\n]+)`", read(path)):
                if NOT_OPERATIONS.match(token) or token in RESULT_PATHS:
                    continue
                if "." in token or token in OPERATIONS:
                    continue
                self.assertTrue(token in ARGUMENTS or token in ERRORS or token in WORDS or token.isupper(),
                                f"{path.name}: `{token}` is no argument, error code or known term")

    def test_every_file_of_the_skill_is_text_the_package_carries(self):
        listed = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
        self.assertIn("install(DIRECTORY integrations/agent-skill DESTINATION share/tomacco)", listed)
        for path in SKILL.rglob("*"):
            if path.is_file():
                path.read_text(encoding="utf-8")


if __name__ == "__main__":
    unittest.main()
