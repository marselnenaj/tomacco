#!/usr/bin/env python3
"""Write the operation reference in docs/reference/ from assets/operations.json,
and its error codes from assets/errors.json.

One page per area (the part of an operation's name before the first dot) and an
index. Each operation has its title, description, what it changes (from its MCP
annotations), every argument with its type, limits, choices, default and
whether it is required, and an example call built the way `tomaccoctl help`
builds it (native/describe.rs).

    python3 tools/build_reference.py          # rewrite docs/reference/ and the agent skill's references/
    python3 tools/build_reference.py --check  # exit 1 when the files are stale
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("docs/reference")
# The agent skill's own, shorter reference: one file per area, loaded only when an agent reads it.
SKILL_OUTPUT = Path("integrations/agent-skill/tomacco/references")
TOP_LEVEL = "general"
HEADER = "<!-- Generated by tools/build_reference.py from assets/operations.json. Do not edit. -->\n"


def load(root=ROOT):
    operations = json.loads((root / "assets/operations.json").read_text(encoding="utf-8"))
    return operations.get("operations", operations) if isinstance(operations, dict) else operations


def load_errors(root=ROOT):
    """{code: {cause, remedy}} from assets/errors.json."""
    return json.loads((root / "assets/errors.json").read_text(encoding="utf-8"))


def errors_page(errors):
    """docs/reference/errors.md: every error code with what it means and what to do."""
    lines = [HEADER.replace("operations.json", "errors.json"), "# Error codes", "",
             f"Every error code `tomaccoctl` returns, {len(errors)} codes, generated from `assets/errors.json`. "
             "A failure is `{\"ok\":false,\"error\":{\"code\":...,\"message\":...,\"remedy\":...}}`, and over MCP "
             "the same object under `structuredContent.error`. Branch on `code`. The message says what happened "
             "this time; when the place that failed has no remedy of its own, `remedy` is the general one below. "
             "In the middle column, … stands for a value the message fills in. [All operations](README.md).", "",
             "| Code | What it means | What to do |", "| --- | --- | --- |"]
    for code, entry in sorted(errors.items()):
        lines.append(f"| `{code}` | {escape(entry['cause'])} | {escape(entry['remedy'])} |")
    return "\n".join(lines) + "\n"


def area(name):
    return name.split(".")[0] if "." in name else TOP_LEVEL


def compact(value):
    """A JSON value as serde_json writes it: no spaces, Unicode kept."""
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def example(schema):
    """The arguments of the example call, as native/describe.rs `example` makes them:
    every required key with its default, first choice, lower limit or a placeholder."""
    out = {}
    properties = schema.get("properties", {})
    for key in schema.get("required", []):
        out[key] = example_value(key, properties.get(key, {}))
    needed = schema.get("minProperties", 0)
    for key, spec in properties.items():
        if len(out) >= needed:
            break
        if key not in out:
            out[key] = example_value(key, spec)
    if len(out) < needed and isinstance(schema.get("additionalProperties"), dict):
        out["<name>"] = example_value("name", schema["additionalProperties"])
    return out


def example_value(key, spec):
    if "default" in spec:
        return spec["default"]
    if spec.get("enum"):
        return spec["enum"][0]
    kind = spec.get("type", "")
    if kind in ("integer", "number"):
        return spec.get("minimum", 1)
    if kind == "boolean":
        return True
    if kind == "array":
        item = example_value(key[:-1] if key.endswith("s") else key, spec.get("items", {}))
        return [item] * max(spec.get("minItems", 0), 1)
    if kind == "object":
        return example(spec)
    return f"<{key}>"


def example_call(operation):
    arguments = example(operation["inputSchema"])
    line = f"tomaccoctl call {operation['name']}"
    if arguments:
        line += " '%s'" % compact(arguments).replace("'", "'\\''")
    return line


def escape(text):
    """Prose from the schema, safe in Markdown and in a table cell."""
    for character, replacement in (("\\", "\\\\"), ("<", "&lt;"), (">", "&gt;"), ("*", "\\*"),
                                   ("|", "\\|"), ("[", "\\["), ("]", "\\]")):
        text = text.replace(character, replacement)
    return " ".join(text.split())


def code(value):
    """Inline code for a value; a backtick inside would end it, so it widens the fence."""
    text = value if isinstance(value, str) else compact(value)
    fence = "``" if "`" in text else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{text}{pad}{fence}".replace("|", "\\|")


def type_name(spec):
    kind = spec.get("type", "")
    if kind == "array":
        item = spec.get("items", {}).get("type", "")
        return f"array of {item}" if item else "array"
    return kind or "any"


def limits(spec):
    """Choices, ranges, lengths, counts and patterns of one argument, as phrases."""
    parts = []
    if "enum" in spec:
        parts.append("one of " + ", ".join(code(choice) for choice in spec["enum"]))
    if "enum" in spec.get("items", {}):
        parts.append("items one of " + ", ".join(code(choice) for choice in spec["items"]["enum"]))
    low, high = spec.get("minimum"), spec.get("maximum")
    if low is not None and high is not None:
        parts.append(f"{low} to {high}")
    elif low is not None:
        parts.append(f"at least {low}")
    elif high is not None:
        parts.append(f"at most {high}")
    low, high = spec.get("minLength", 0), spec.get("maxLength")
    if high is not None:
        parts.append(f"{'non-empty, ' if low == 1 else ''}up to {high} characters" if low <= 1
                     else f"{low} to {high} characters")
    elif low == 1:
        parts.append("non-empty")
    elif low > 1:
        parts.append(f"at least {low} characters")
    low, high = spec.get("minItems", 0), spec.get("maxItems")
    if high is not None:
        parts.append(f"up to {high} items" if low == 0 else f"{low} to {high} items")
    elif low > 0:
        parts.append(f"at least {low} item{'s' if low != 1 else ''}")
    if "pattern" in spec:
        parts.append("matching " + code(spec["pattern"]))
    return parts


def rows(schema, prefix=""):
    """One table row per argument, nested object keys as `parent.key` and items of an
    array of objects as `parent[].key`."""
    required = set(schema.get("required", []))
    for key, spec in schema.get("properties", {}).items():
        name = prefix + key
        details = limits(spec)
        if spec.get("description"):
            details.append(escape(spec["description"]))
        default = code(compact(spec["default"])) if "default" in spec else ""
        yield (f"`{name}`", type_name(spec), "yes" if key in required else "", default,
               "; ".join(details))
        if spec.get("type") == "object" and spec.get("properties"):
            yield from rows(spec, name + ".")
        items = spec.get("items", {})
        if spec.get("type") == "array" and items.get("type") == "object" and items.get("properties"):
            yield from rows(items, name + "[].")


def effect(annotations):
    """The MCP annotations as one line: read, write or destructive, then idempotent and open world."""
    if annotations.get("readOnlyHint"):
        words = ["read-only"]
    elif annotations.get("destructiveHint"):
        words = ["**destructive**"]
    else:
        words = ["writes"]
    words.append("idempotent" if annotations.get("idempotentHint") else "not idempotent")
    words.append("open world" if annotations.get("openWorldHint") else "closed world")
    return "Annotations: " + ", ".join(words) + "."


def operation_section(operation):
    lines = [f"### {operation['name']}", "", f"**{escape(operation.get('title', ''))}**", ""]
    if operation.get("description"):
        lines += [escape(operation["description"]), ""]
    lines += [effect(operation.get("annotations", {})), ""]
    table = list(rows(operation["inputSchema"]))
    if table:
        lines += ["| Argument | Type | Required | Default | Details |", "| --- | --- | --- | --- | --- |"]
        lines += ["| " + " | ".join(row) + " |" for row in table]
    else:
        lines.append("Takes no arguments.")
    lines += ["", "```sh", example_call(operation), "```", ""]
    return lines


def anchor(name):
    return name.replace(".", "")


def pages(operations, errors=None):
    """{relative path: text} of every reference page."""
    errors = load_errors() if errors is None else errors
    groups = {}
    for operation in operations:
        groups.setdefault(area(operation["name"]), []).append(operation)
    names = sorted(groups, key=lambda name: (name != TOP_LEVEL, name))
    out = {}
    index = [HEADER, "# Operation reference", "",
             f"Every `tomaccoctl` operation, {len(operations)} in all, generated from `assets/operations.json`, "
             "the schema `tomaccoctl schema` prints and the MCP server offers as tools. Over MCP the operation "
             "name is the tool name.", "",
             "Each entry gives the arguments with their types, limits and defaults, what the operation changes "
             "(from its MCP annotations) and an example call made from the schema, the same one "
             "`tomaccoctl help OPERATION` prints. Values in angle brackets are placeholders. The "
             "[agent guide](../agents.md) explains jobs, errors and the workflows that combine these.", "",
             "The annotations are the hints MCP clients see. **Read-only** changes nothing. **Writes** changes "
             "state but is not marked as deleting data. **Destructive** may delete or overwrite data: ask the "
             "user first. **Idempotent** means repeating the call with the same arguments has no further effect. "
             "**Open world** means it reaches beyond Tomacco's own state: devices, tools, files or the network.", "",
             f"[Error codes](errors.md) lists all {len(errors)} error codes with what each means and what to do.", ""]
    for name in names:
        page = f"{name}.md"
        title = "Top-level operations" if name == TOP_LEVEL else f"`{name}` operations"
        index += [f"## [{name}]({page})", "", "| Operation | Title | Annotation |", "| --- | --- | --- |"]
        body = [HEADER, f"# {title}", "",
                f"{len(groups[name])} operation{'s' if len(groups[name]) != 1 else ''}. Generated from `assets/operations.json`; "
                "[all areas](README.md).", ""]
        for operation in groups[name]:
            hints = operation.get("annotations", {})
            kind = ("read-only" if hints.get("readOnlyHint") else "**destructive**" if hints.get("destructiveHint")
                    else "writes")
            index.append(f"| [`{operation['name']}`]({page}#{anchor(operation['name'])}) | "
                         f"{escape(operation.get('title', ''))} | {kind} |")
            body += operation_section(operation)
        index.append("")
        out[OUTPUT / page] = "\n".join(body).rstrip("\n") + "\n"
    out[OUTPUT / "README.md"] = "\n".join(index).rstrip("\n") + "\n"
    out[OUTPUT / "errors.md"] = errors_page(errors)
    out.update(skill_pages(operations, errors))
    return out


