def skill_area(name):
    top = area(name)
    parts = name.split(".")
    if top in SPLIT and len(parts) > 2 and parts[1] in SPLIT[top]:
        return SPLIT[top][parts[1]]
    return top


def clip(text, limit):
    """The text on one line, cut at a word and ended with … when it is longer than limit."""
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:(") + "…"


def short_type(spec):
    kind = type_name(spec)
    properties = spec.get("properties") if spec.get("type") == "object" else spec.get("items", {}).get("properties")
    if properties:
        kind += " {" + ", ".join(properties) + "}"
    return kind


def argument_line(key, spec, required):
    notes = [part.replace("`", "") for part in limits(spec)]
    if "default" in spec:
        notes.append("default " + compact(spec["default"]))
    detail = f" ({'; '.join(notes)})" if notes else ""
    text = clip(spec.get("description", ""), 160)
    return f"- `{key}` {short_type(spec)}{', required' if required else ''}{detail}" + (f": {text}" if text else "")


def skill_effect(annotations):
    if annotations.get("readOnlyHint"):
        words = ["read-only"]
    elif annotations.get("destructiveHint"):
        words = ["**destructive, ask first**"]
    else:
        words = ["writes"]
    if annotations.get("idempotentHint"):
        words.append("idempotent")
    return ", ".join(words)


def skill_operation(operation):
    schema = operation["inputSchema"]
    required = set(schema.get("required", []))
    properties = schema.get("properties", {})
    lines = [f"### {operation['name']}", "",
             f"{operation.get('title', '')}. {skill_effect(operation.get('annotations', {}))}.", ""]
    if operation.get("description"):
        lines += [" ".join(operation["description"].split()), ""]
    ordered = [key for key in properties if key in required] + [key for key in properties if key not in required]
    if ordered:
        lines += [argument_line(key, properties[key], key in required) for key in ordered]
    else:
        lines.append("No arguments.")
    lines += ["", "```sh", example_call(operation), "```", ""]
    return lines


def skill_pages(operations, errors):
    """{relative path: text} of the agent skill's references: one file per area, errors.md and index.md."""
    groups = {}
    for operation in operations:
        groups.setdefault(skill_area(operation["name"]), []).append(operation)
    names = sorted(groups, key=lambda name: (name != TOP_LEVEL, name))
    out = {}
    index = [SKILL_HEADER, "# Tomacco references", "",
             f"{len(operations)} operations in all, in {len(names)} files, one per area. Read the file of the area you need, "
             "not all of them. Each operation lists its arguments (required first) and one example call; "
             "`tomaccoctl help OPERATION` prints the same with the full argument descriptions. "
             "[Error codes](errors.md).", "",
             "| File | Operations | Areas and names |", "| --- | --- | --- |"]
    for name in names:
        group = groups[name]
        title = "Top-level operations" if name == TOP_LEVEL else f"`{name}` operations"
        body = [SKILL_HEADER, f"# {title}", "", f"{len(group)} operation{'s' if len(group) != 1 else ''}. "
                "Generated from `assets/operations.json`; [all references](index.md).", ""]
        for operation in group:
            body += skill_operation(operation)
        out[SKILL_OUTPUT / f"{name}.md"] = "\n".join(body).rstrip("\n") + "\n"
        note = AREA_NOTES.get(name, "")
        listing = ", ".join(f"`{operation['name']}`" for operation in group[:3]) + (", …" if len(group) > 3 else "")
        index.append(f"| [{name}]({name}.md) | {len(group)} | {note + ' ' if note else ''}{listing} |")
    out[SKILL_OUTPUT / "index.md"] = "\n".join(index).rstrip("\n") + "\n"
    lines = [SKILL_HEADER, "# Error codes", "",
             f"{len(errors)} codes. A failure is `{{\"ok\":false,\"error\":{{\"code\":...,\"message\":...,\"remedy\":...}}}}`. "
             "Branch on `code`, show `message`, follow `remedy`. The remedy in the call's own answer can be "
             "more specific than the general one here; a … in the meaning stands for a value the message fills in.", "",
             "| Code | Meaning | Remedy |", "| --- | --- | --- |"]
    for code_name, entry in sorted(errors.items()):
        lines.append(f"| `{code_name}` | {escape(entry['cause'])} | {escape(entry['remedy'])} |")
    out[SKILL_OUTPUT / "errors.md"] = "\n".join(lines) + "\n"
    return out


def stale(root=ROOT):
    """Paths whose checked-in text differs from what the schema gives, and extra pages."""
    wanted = pages(load(root), load_errors(root))
    found = [str(path) for path, text in wanted.items()
             if not (root / path).is_file() or (root / path).read_text(encoding="utf-8") != text]
    for output in (OUTPUT, SKILL_OUTPUT):
        directory = root / output
        if directory.is_dir():
            found += [str(output / path.name) for path in sorted(directory.glob("*.md")) if output / path.name not in wanted]
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="report stale pages and exit 1 instead of writing")
    arguments = parser.parse_args(argv)
    if arguments.check:
        found = stale()
        if found:
            print("stale: " + ", ".join(found) + "; run python3 tools/build_reference.py", file=sys.stderr)
            return 1
        return 0
    wanted = pages(load())
    for output in (OUTPUT, SKILL_OUTPUT):
        (ROOT / output).mkdir(parents=True, exist_ok=True)
        for path in sorted((ROOT / output).glob("*.md")):
            if output / path.name not in wanted:
                path.unlink()
    for path, text in wanted.items():
        (ROOT / path).write_text(text, encoding="utf-8")
    print(f"wrote {len(wanted)} pages to {OUTPUT} and {SKILL_OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
